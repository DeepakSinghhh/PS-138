"""Markdown + figure writers for benchmark results."""

from __future__ import annotations

from pathlib import Path

import numpy as np

from greenfleet.config import REPORTS_DIR

FIG_DIR = REPORTS_DIR / "figures"


def _plt():
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    plt.rcParams.update({"figure.dpi": 110, "axes.spines.top": False, "axes.spines.right": False,
                         "axes.grid": True, "grid.alpha": 0.25, "font.size": 9})
    return plt


def _fmt(v, nd=3):
    if v is None:
        return "-"
    if isinstance(v, float):
        return f"{v:.{nd}f}"
    return str(v)


def _table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(headers)) + "|"]
    out += ["| " + " | ".join(_fmt(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def prediction_figures(res: dict) -> dict[str, str]:
    plt = _plt()
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    figs = {}
    tuners = res.get("tuners", {})
    if tuners:
        fig, ax = plt.subplots(figsize=(6, 3.4))
        for name, v in tuners.items():
            ax.plot(np.arange(1, len(v["mean_history"]) + 1), v["mean_history"], label=name,
                    lw=2.2 if name == "QPSO" else 1.2)
        ax.set_xlabel("objective evaluations")
        ax.set_ylabel("best validation MAE (t/day)")
        ax.set_title("Hyperparameter search convergence (equal budget)")
        ax.legend(frameon=False, ncol=2)
        fig.tight_layout()
        path = FIG_DIR / "tuner_convergence.png"
        fig.savefig(path)
        plt.close(fig)
        figs["tuner_convergence"] = path.name
    sc = res["scenarios"].get("A_known_ships", {})
    mps = sc.get("qphys_report", {}).get("mps")
    if mps:
        fig, ax = plt.subplots(figsize=(6.5, 3.2))
        s = mps["entanglement_entropy"]
        ax.bar(np.arange(len(s)), s, color="#2a78b8")
        ax.set_xticks(np.arange(len(s)))
        ax.set_xticklabels(mps["bond_features"], rotation=70, ha="right", fontsize=7)
        ax.set_ylabel("entanglement entropy (nats)")
        ax.set_title("MPS bond entanglement: where the model couples features")
        fig.tight_layout()
        path = FIG_DIR / "mps_entanglement.png"
        fig.savefig(path)
        plt.close(fig)
        figs["mps_entanglement"] = path.name
    return figs


def prediction_markdown(res: dict, figs: dict[str, str]) -> str:
    md = ["# Prediction benchmark", "",
          "Generated by `make bench-quick` / `make bench-full`. All numbers are on held-out test data.", "",
          "Data: physics-informed synthetic fleet telemetry (10 vessel classes, 20 ships, speed, cargo load, "
          "weather and vessel type as inputs). When FuelCast is placed in `data/raw/fuelcast`, scenario D reports "
          "results on real data.", ""]
    for key, sc in res["scenarios"].items():
        if "skipped" in sc:
            md += [f"## {key}", "", f"*Skipped: {sc['skipped']}*", ""]
            continue
        md += [f"## {sc['scenario']}", "",
               f"Train rows: {sc['rows']['train']:,}; test rows: {sc['rows']['test']:,}; ships in test: {sc['ships_in_test']}", ""]
        rows = [[r["model"], r.get("MAPE"), r.get("MAE"), r.get("RMSE"), r.get("R2"), r.get("seconds")]
                for r in sc["results"] if "MAPE" in r]
        md += [_table(["Model", "MAPE %", "MAE t/d", "RMSE t/d", "R²", "fit s"], rows), ""]
        c = sc["conformal"]
        md += [f"Q-PHYS 90 % conformal interval: empirical coverage **{c['coverage']:.3f}**, "
               f"relative half-width ±{c['relative_half_width'] * 100:.1f} %.", ""]
        if sc.get("wilcoxon_vs_qphys"):
            trows = [[m, v["p_value"], f"{v['qphys_better_on']}/{v['ships']}"] for m, v in sc["wilcoxon_vs_qphys"].items()]
            md += ["Wilcoxon signed-rank test on per-ship MAE (H1: Q-PHYS error is lower):", "",
                   _table(["Baseline", "p-value", "ships where Q-PHYS better"], trows), ""]
    if res.get("tuners"):
        md += ["## Hyperparameter tuning: convergence speed and quality", "",
               f"Equal budget of {res['config']['tuner_budget']} evaluations, {res['config']['tuner_seeds']} seed(s).", ""]
        rows = [[k, v["best_val_mae_mean"], v["best_val_mae_std"], v["evals_to_within_1pct"], v["seconds"]]
                for k, v in sorted(res["tuners"].items(), key=lambda kv: kv[1]["best_val_mae_mean"])]
        md += [_table(["Tuner", "best val MAE", "sd", "evals to ≤1 % of best", "seconds"], rows), ""]
        if "tuner_convergence" in figs:
            md += [f"![tuner convergence](figures/{figs['tuner_convergence']})", ""]
    if res.get("feature_selection"):
        md += ["## Feature selection", "",
               "Speed, load, weather and vessel type are mandatory inputs (PS Delivery Table); the search covers the rest.", ""]
        rows = [[k, v["score_mean"], v["n_features"], v["evaluations"]] for k, v in res["feature_selection"].items()]
        md += [_table(["Method", "penalised val MAE", "features", "evaluations"], rows), ""]
    if "mps_entanglement" in figs:
        md += ["## Inside the quantum-inspired model", "",
               "Entanglement entropy across each bond of the trained Matrix Product State shows where the model "
               "carries correlations between neighbouring features.", "",
               f"![MPS entanglement](figures/{figs['mps_entanglement']})", ""]
    md += [f"*Benchmark runtime: {res['seconds'] / 60:.1f} min.*", ""]
    return "\n".join(md)


def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
