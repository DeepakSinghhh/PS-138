def optimization_figures(res: dict) -> dict[str, str]:
    plt = _plt()
    FIG_DIR.mkdir(parents=True, exist_ok=True)
    figs = {}
    for key, inst in res["instances"].items():
        fig, ax = plt.subplots(figsize=(6, 3.4))
        for name, c in inst["curves"].items():
            ax.plot(c["nfe"], c["hv_mean"], label=name, lw=2.4 if "ours" in name else 1.2)
        ax.axhline(0.95 * inst["reference_hv"], color="grey", ls=":", lw=1)
        ax.set_xlabel("fleet plans evaluated")
        ax.set_ylabel("hypervolume (normalised)")
        ax.set_title(f"Convergence: {key}")
        ax.legend(frameon=False, fontsize=7, ncol=2)
        fig.tight_layout()
        path = FIG_DIR / f"convergence_{key}.png"
        fig.savefig(path)
        plt.close(fig)
        figs[f"convergence_{key}"] = path.name
    ex = res.get("exact")
    if ex:
        fig, ax = plt.subplots(figsize=(5.5, 3.6))
        f = np.array(ex["exact_front_cost_vs_emissions"])
        ax.plot(f[:, 0] / 1e3, f[:, 1], "k-o", ms=3, label="exact MILP front (discretised speeds)")
        ax.set_xlabel("WtW GHG (kt CO2e / yr)")
        ax.set_ylabel("cost (M USD / yr)")
        ax.set_title("India 2030: exact cost-emissions trade-off")
        ax.legend(frameon=False, fontsize=7)
        fig.tight_layout()
        path = FIG_DIR / "exact_front_india.png"
        fig.savefig(path)
        plt.close(fig)
        figs["exact_front"] = path.name
    sc = res.get("scalability", {}).get("rows")
    if sc:
        fig, ax = plt.subplots(figsize=(5.5, 3.4))
        names = list(sc[0]["algorithms"])
        for name in names:
            ax.plot([r["routes"] for r in sc], [r["algorithms"][name]["seconds_mean"] for r in sc], "-o", ms=3,
                    label=name, lw=2.2 if "ours" in name else 1.2)
        ax.plot([r["routes"] for r in sc], [r["milp_min_cost_seconds"] for r in sc], "k--", label="MILP (single objective)")
        ax.set_xlabel("routes in network")
        ax.set_ylabel("wall time (s)")
        ax.set_title("Scalability")
        ax.legend(frameon=False, fontsize=7)
        fig.tight_layout()
        path = FIG_DIR / "scalability.png"
        fig.savefig(path)
        plt.close(fig)
        figs["scalability"] = path.name
    return figs


def optimization_markdown(res: dict, figs: dict[str, str]) -> str:
    cfg = res["config"]
    md = ["# Optimization benchmark", "",
          "Generated by `make bench` (this configuration) — `make bench-quick` is a 3-seed smoke run, `make bench-full` "
          "uses 30 seeds and larger budgets. Every algorithm evaluates fleet plans through the same tracker (identical "
          "budgets, identical feasibility rules), and front quality is measured on normalised objectives (fuel, WtW "
          "emissions, cost) with a common reference front per instance.", "",
          f"Budget: {cfg['budget']:,} plan evaluations per run, {cfg['seeds']} seeds per algorithm "
          f"(large-scale network: {cfg['large_budget']:,} evaluations, {cfg.get('large_seeds', '-')} seeds; "
          f"scalability sweep: {cfg['scal_seeds']} seed(s) per size).", "",
          "Tuning disclosure: QMOEA-H hyperparameters were set on the India instance. The one exception is the rate of "
          "the route-wise merge operator (0.5 vs 1.0), chosen after comparing India, EU and the 50/100-route synthetic "
          "networks of the scalability sweep (generator seed 7); the 100-route large-scale network (generator seed 11) "
          "was never used for tuning.", ""]
    for key, inst in res["instances"].items():
        md += [f"## {key}", ""]
        if "current_practice" in inst:
            cp = inst["current_practice"]
            md += ["Current-practice reference plan (VLSFO, fastest schedule-feasible speed, no shore power): " +
                   ", ".join(f"{k} = {v:,.1f}" for k, v in cp.items()), ""]
        rows = []
        for name, t in sorted(inst["table"].items(), key=lambda kv: -kv[1]["hv_mean"]):
            b = t["best_objective_mean"]
            rows.append([name, t["hv_mean"], t["hv_std"], t["igd_plus_mean"], t["nfe_to_95pct_ref_hv"],
                         f"{t['feasible_runs']}/{t['runs']}",
                         b.get("fuel"), b.get("emissions"), b.get("cost"), t["seconds_mean"]])
        md += [_table(["Algorithm", "HV", "sd", "IGD+", "evals to 95 % ref HV", "feasible",
                       "best fuel t", "best GHG t", "best cost M$", "s"], rows), ""]
        if inst.get("mann_whitney_vs_ours"):
            trows = [[n, v["p_value"], "yes" if v["ours_better"] else "no"] for n, v in inst["mann_whitney_vs_ours"].items()]
            md += ["Mann-Whitney U on hypervolume (H1: QMOEA-H higher):", "", _table(["vs", "p-value", "QMOEA-H mean higher"], trows), ""]
        if inst.get("friedman"):
            fr = inst["friedman"]
            ranks = sorted(fr["mean_rank"].items(), key=lambda kv: kv[1])
            md += [f"Friedman test p = {fr['p_value']:.3g}; mean ranks: " + ", ".join(f"{n} {r:.2f}" for n, r in ranks), ""]
        k = f"convergence_{key}"
        if k in figs:
            md += [f"![{k}](figures/{figs[k]})", ""]
    ex = res.get("exact")
    if ex:
        md += ["## Exact reference (MILP) and optimality gaps", "",
               "With speeds discretised to 5 levels the multiple-choice MILP is exact. Options per route after dominance "
               f"pruning: {ex['options_per_route']}. MILP time for all extremes and a 12-point ε-front: {ex['milp_seconds_total']:.1f} s.", ""]
        md += ["Exact optima: " + ", ".join(f"{k} = {v['value']:,.1f}" for k, v in ex["exact_extremes"].items()), ""]
        rows = [[n, a["gap_pct_mean"].get("fuel"), a["gap_pct_mean"].get("emissions"), a["gap_pct_mean"].get("cost"),
                 a["igd_plus_vs_exact_front"], a["feasible_runs"]] for n, a in ex["algorithms"].items()]
        md += [_table(["Algorithm", "fuel gap %", "GHG gap %", "cost gap %", "IGD+ vs exact front", "feasible runs"], rows), ""]
        if "exact_front" in figs:
            md += [f"![exact front](figures/{figs['exact_front']})", ""]
    qb = res.get("qubo")
    if qb:
        md += ["## QUBO + (simulated) quantum annealing", "",
               "Fleet QUBO with one-hot route variables, lazily added availability penalties and a Lagrangian FuelEU "
               "price. Gap = weighted objective of the annealed plan vs the exact MILP optimum of the same weighted "
               "objective (evaluated with the exact fleet model).", ""]
        rows = []
        for net, rs in qb.items():
            for r in rs:
                w = "/".join(f"{k[:4]} {v:.2f}" for k, v in r["weights"].items())
                for s, v in r["solvers"].items():
                    rows.append([net, w, s, v["gap_pct_median"], v["gap_pct_mean"], v["feasible_share"], v["seconds_mean"]])
        md += [_table(["network", "weights", "solver", "median gap %", "mean gap %", "feasible", "s"], rows), ""]
    sc = res.get("scalability")
    if sc:
        md += ["## Scalability", "",
               f"Synthetic networks (generator seed 7), budget = {cfg['budget']:,} x sqrt(routes / 12) evaluations, "
               f"{cfg['scal_seeds']} seed(s) per method; HV is normalised per network across the methods shown. "
               "The cost gap compares each method's cheapest plan (mean over seeds) with the exact MILP minimum-cost plan "
               "(speeds discretised to 5 levels).", ""]
        rows = []
        for r in sc["rows"]:
            for n, a in r["algorithms"].items():
                rows.append([r["routes"], r["ships_available"], n, a["hv_mean"], a["cost_gap_pct_vs_milp"], a["seconds_mean"],
                             a["ms_per_1000_evals"]])
            rows.append([r["routes"], r["ships_available"], "MILP min-cost", None, 0.0, r["milp_min_cost_seconds"], None])
        md += [_table(["routes", "ships available", "method", "HV", "cost gap % vs MILP", "s", "ms / 1000 evals"], rows), ""]
        if "scalability" in figs:
            md += [f"![scalability](figures/{figs['scalability']})", ""]
    md += [f"*Benchmark runtime: {res['seconds'] / 60:.1f} min.*", ""]
    return "\n".join(md)
